use super::PublicKey;

/// RFC 8032 section 7.1, test 1: the secret key, then the public key it derives.
#[rustfmt::skip]
const RFC_8032_SECRET: [u8; 32] = [
    0x9d, 0x61, 0xb1, 0x9d, 0xef, 0xfd, 0x5a, 0x60, 0xba, 0x84, 0x4a, 0xf4, 0x92, 0xec, 0x2c, 0xc4,
    0x44, 0x49, 0xc5, 0x69, 0x7b, 0x32, 0x69, 0x19, 0x70, 0x3b, 0xac, 0x03, 0x1c, 0xae, 0x7f, 0x60,
];
#[rustfmt::skip]
const RFC_8032_PUBLIC: [u8; 32] = [
    0xd7, 0x5a, 0x98, 0x01, 0x82, 0xb1, 0x0a, 0xb7, 0xd5, 0x4b, 0xfe, 0xd3, 0xc9, 0x64, 0x07, 0x3a,
    0x0e, 0xe1, 0x72, 0xf3, 0xda, 0xa6, 0x23, 0x25, 0xaf, 0x02, 0x1a, 0x68, 0xf7, 0x07, 0x51, 0x1a,
];

#[test]
fn a_seed_derives_the_rfc_8032_public_key() {
    assert_eq!(
        PublicKey::of_seed(&RFC_8032_SECRET).bytes(),
        &RFC_8032_PUBLIC
    );
}

#[test]
fn distinct_seeds_derive_distinct_keys() {
    assert_ne!(PublicKey::of_seed(&[1; 32]), PublicKey::of_seed(&[2; 32]));
}
