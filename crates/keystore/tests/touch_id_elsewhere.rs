/// The `touch-id` record's place in the golden file: after the header, the count, and the passphrase
/// record, up to the seed's nonce.
const TOUCH_ID_RECORD: core::ops::Range<usize> = 147..388;

/// The wait a touch would get. Nothing here asks for one: a build without an enclave refuses first.
const WAIT: Duration = Duration::from_secs(60);

fn passphrase(text: &str) -> Passphrase {
    Passphrase::new(Zeroizing::new(text.as_bytes().to_vec())).unwrap()
}

fn touch() -> Unlock<'static> {
    Unlock::TouchId {
        reason: "open the test key",
        wait: WAIT,
    }
}

/// The golden file at a fresh path, owner-only, and the directory to remove after.
fn golden_file(name: &str) -> (KeyFile, PathBuf) {
    let dir =
        std::env::temp_dir().join(format!("keystore-elsewhere-{name}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir(&dir).unwrap();
    let path = dir.join("standard.key");
    fs::write(&path, GOLDEN_TOUCH_ID).unwrap();
    fs::set_permissions(&path, fs::Permissions::from_mode(0o600)).unwrap();
    (KeyFile::new(path), dir)
}

fn locked(file: &KeyFile) -> keystore::Locked {
    match file.load().unwrap() {
        Some(Stored::Locked(locked)) => locked,
        other => panic!("expected a locked file, found {other:?}"),
    }
}

fn unavailable<T: core::fmt::Debug>(outcome: Result<T, Error>) -> bool {
    matches!(
        outcome,
        Err(Error::TouchId {
            source: TouchIdError::Unavailable,
            ..
        })
    )
}

#[test]
fn a_touch_id_lock_is_read_and_kept_and_the_passphrase_opens_the_file() {
    let (file, dir) = golden_file("read");
    let under = passphrase("correct horse battery staple");
    let locked = locked(&file);

    assert_eq!(
        locked.methods().collect::<Vec<_>>(),
        [Method::Passphrase, Method::TouchId]
    );
    assert_eq!(locked.health(Method::Passphrase), Some(Health::Live));
    assert_eq!(locked.health(Method::TouchId), Some(Health::Dead));
    let secret = locked.unlock(Unlock::Passphrase(&under)).unwrap();
    secret.with_bytes(|seed| assert_eq!(seed, &core::array::from_fn::<u8, 32, _>(|at| at as u8)));
    assert!(unavailable(locked.unlock(touch())));

    // A new passphrase keeps the touch-id lock exactly as it was.
    let new = passphrase("a new passphrase for it");
    file.add_lock(Some(Unlock::Passphrase(&under)), NewLock::Passphrase(&new))
        .unwrap();
    let after = fs::read(file.path()).unwrap();
    assert_eq!(after[TOUCH_ID_RECORD], GOLDEN_TOUCH_ID[TOUCH_ID_RECORD]);
    fs::remove_dir_all(dir).unwrap();
}

#[test]
fn nothing_here_makes_or_opens_a_touch_id_lock_or_leaves_one_alone() {
    let (file, dir) = golden_file("refuse");
    let under = passphrase("correct horse battery staple");
    let before = fs::read(file.path()).unwrap();

    assert!(matches!(
        file.remove_lock(Unlock::Passphrase(&under), Method::Passphrase),
        Err(Error::NoneOpensHere {
            method: Method::Passphrase,
            ..
        })
    ));
    assert!(unavailable(file.add_lock(
        Some(Unlock::Passphrase(&under)),
        NewLock::TouchId {
            reason: "lock it",
            wait: WAIT,
        }
    )));
    assert_eq!(fs::read(file.path()).unwrap(), before);

    let fresh = KeyFile::new(dir.join("fresh.key"));
    assert!(unavailable(fresh.write(
        &Secret::generate().unwrap(),
        Protection::TouchId {
            reason: "write it",
            wait: WAIT,
        }
    )));
    assert!(fresh.load().unwrap().is_none());
    fs::remove_dir_all(dir).unwrap();
}
